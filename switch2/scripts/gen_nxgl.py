"""Generate warsmash/backend/native/nxgl.h + nxgl.c: a GL loader for the Switch 2.

    python -I scripts/gen_nxgl.py [path/to/GL/glcorearb.h]

The Switch 2 has no libGL: desktop GL (Mesa's zink on NVK) is reached only through
eglGetProcAddress, as probe A did. The loader holds one pointer per core function of
GL 1.0 .. 4.6 (SwitchGDX's GLES2-style calls such as glClearDepthf are core from 4.1) and
`#define`s each name to its pointer, so code written against plain gl* calls (SwitchGDX's
natives) compiles unchanged. nxglLoad() fills them after eglMakeCurrent and returns how many
the driver did not give.
"""
import re
import sys
from pathlib import Path

HEADER = Path(sys.argv[1] if len(sys.argv) > 1 else "C:/devkitPro/portlibs/switch2/include/GL/glcorearb.h")
OUT = Path(__file__).resolve().parent.parent / "warsmash" / "backend" / "native"


def main():
    text = HEADER.read_text(encoding="utf-8")
    functions = []
    version = None
    for line in text.splitlines():
        m = re.match(r"#ifndef (GL_VERSION_\d_\d)$", line)
        if m:
            version = m.group(1)
            continue
        m = re.match(r"#ifndef (GL_[A-Z0-9]+_\w+)$", line)
        if m and not m.group(1).startswith("GL_VERSION_"):
            version = None  # an extension block: not loaded
            continue
        m = re.match(r"GLAPI .*?APIENTRY (gl\w+) \(", line)
        if m and version:
            functions.append((m.group(1), version))
    names = [f for f, _ in functions]
    assert len(names) == len(set(names)), "duplicate GL function"
    assert "glDrawElementsInstanced" in names and "glClearDepthf" in names and "glDrawBuffers" in names

    h = ["// Generated by scripts/gen_nxgl.py from glcorearb.h: do not edit.",
         "// GL 1.0 .. 4.6 core through eglGetProcAddress (the Switch 2 has no libGL).",
         "#pragma once",
         "#include <GL/glcorearb.h>",
         "",
         "#ifdef __cplusplus",
         'extern "C" {',
         "#endif",
         "",
         "/// Fills every pointer with eglGetProcAddress (a current context is needed first). Returns the",
         "/// number of functions the driver did not give; their names go to `missing` (comma separated,",
         "/// truncated to `size`) when it is set.",
         "int nxglLoad(char *missing, int size);",
         ""]
    for name, _ in functions:
        h.append(f"extern PFN{name.upper()}PROC nxgl_{name};")
    h += ["", "#ifdef __cplusplus", "}", "#endif", ""]
    for name, _ in functions:
        h.append(f"#define {name} nxgl_{name}")
    h.append("")

    c = ["// Generated by scripts/gen_nxgl.py from glcorearb.h: do not edit.",
         '#include "nxgl.h"',
         "#include <EGL/egl.h>",
         "#include <string.h>",
         ""]
    for name, _ in functions:
        c.append(f"PFN{name.upper()}PROC nxgl_{name};")
    c += ["",
          "struct nxgl_entry { const char *name; void **slot; };",
          "static const struct nxgl_entry nxgl_entries[] = {"]
    for name, version in functions:
        c.append(f'    {{"{name}", (void **) &nxgl_{name}}}, /* {version} */')
    c += ["};",
          "",
          "int nxglLoad(char *missing, int size) {",
          "    int count = 0, used = 0;",
          "    if (missing && size > 0)",
          "        missing[0] = 0;",
          "    for (unsigned i = 0; i < sizeof(nxgl_entries) / sizeof(nxgl_entries[0]); i++) {",
          "        void *f = (void *) eglGetProcAddress(nxgl_entries[i].name);",
          "        *nxgl_entries[i].slot = f;",
          "        if (f)",
          "            continue;",
          "        count++;",
          "        int n = (int) strlen(nxgl_entries[i].name);",
          "        if (missing && used + n + 2 < size) {",
          "            if (used)",
          "                missing[used++] = ',';",
          "            memcpy(missing + used, nxgl_entries[i].name, n + 1);",
          "            used += n;",
          "        }",
          "    }",
          "    return count;",
          "}",
          ""]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "nxgl.h").write_text("\n".join(h), encoding="utf-8", newline="\n")
    (OUT / "nxgl.c").write_text("\n".join(c), encoding="utf-8", newline="\n")
    print(f"{len(functions)} GL functions -> {OUT / 'nxgl.h'}, nxgl.c")


if __name__ == "__main__":
    main()
