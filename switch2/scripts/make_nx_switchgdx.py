DEFINED = {"__SWITCH__": True, "__WIN32__": False, "__WINRT__": False, "__APPLE__": False}


def resolve(text):
    """Keeps the __SWITCH__ side of every #if/#ifdef on the names in DEFINED (others untouched)."""
    out, stack = [], []  # stack of (known, keep, taken)

    def active():
        return all(keep for known, keep, _ in stack if known)

    for line in text.splitlines():
        s = line.strip()
        m = re.match(r"#\s*(if|ifdef|ifndef|elif|else|endif)\b(.*)", s)
        if m:
            kind, rest = m.group(1), m.group(2).strip()
            if kind in ("if", "ifdef", "ifndef"):
                value = evaluate(kind, rest)
                if value is None:
                    stack.append((False, True, False))
                    if active():
                        out.append(line)
                else:
                    stack.append((True, value, value))
                continue
            known, keep, taken = stack[-1]
            if kind == "elif":
                if not known:
                    if active():
                        out.append(line)
                    continue
                value = evaluate("if", rest)
                assert value is not None, line
                stack[-1] = (True, value and not taken, taken or value)
                continue
            if kind == "else":
                if not known:
                    if active():
                        out.append(line)
                    continue
                stack[-1] = (True, not taken, True)
                continue
            if kind == "endif":
                stack.pop()
                if not known and active():
                    out.append(line)
                continue
        if active():
            out.append(line)
    assert not stack
    return "\n".join(out) + "\n"


def evaluate(kind, rest):
    if kind == "ifdef":
        return DEFINED.get(rest)
    if kind == "ifndef":
        v = DEFINED.get(rest)
        return None if v is None else not v
    # `defined(X)`, `defined X` and a bare `X` (upstream has `#elif __APPLE__`)
    expr = re.sub(r"defined\s*\(?\s*(\w+)\s*\)?", lambda m: m.group(1), rest)
    names = re.findall(r"[A-Za-z_]\w*", expr)
    if not names or any(n not in DEFINED for n in names):
        return None
    expr = re.sub(r"[A-Za-z_]\w*", lambda m: str(DEFINED[m.group(0)]), expr)
    expr = expr.replace("||", " or ").replace("&&", " and ").replace("!", " not ")
    return bool(eval(expr, {}))


def between(text, start, end):
    """From the line starting with `start` up to (not including) the line starting with `end`."""
    i = text.index("\n" + start) + 1
    j = text.index("\n" + end, i) + 1
    return text[i:j]


