# LWJGL (the desktop backend Warsmash is written and tested against) sizes these calls from the
# Buffer itself and ignores the int it is passed: glBufferData/glBufferSubData upload remaining()
# elements' bytes, glUniform*v / glUniformMatrix*v take count = remaining() / components, glGen* /
# glDelete* take n = remaining(). Upstream SwitchGL passes the int through, and Warsmash relies on
# LWJGL here: SetupGeosets uploads float[] data with size = element count (1/4 of the bytes) and
# short indices with size = index count (1/2), which tore every MDX model apart on console boot 6.
BUFFER_SIZES = r"""
// warsmash-nx: what LWJGL sizes its GL calls by (scripts/make_nx_switchgdx.py, BUFFER_SIZES)
static jint bufferRemaining(jobject buffer) {
    auto b = (java_nio_Buffer *) buffer;
    return b->F_limit - b->F_position;
}

static jint bufferRemainingBytes(jcontext ctx, jobject buffer) {
    auto b = (java_nio_Buffer *) buffer;
    jint size = 1;
    if (isInstance(ctx, buffer, &class_java_nio_FloatBuffer) || isInstance(ctx, buffer, &class_java_nio_IntBuffer))
        size = 4;
    else if (isInstance(ctx, buffer, &class_java_nio_ShortBuffer) || isInstance(ctx, buffer, &class_java_nio_CharBuffer))
        size = 2;
    else if (isInstance(ctx, buffer, &class_java_nio_LongBuffer) || isInstance(ctx, buffer, &class_java_nio_DoubleBuffer))
        size = 8;
    return (b->F_limit - b->F_position) * size;
}

"""


def lwjgl_sizes(gl):
    """Rewrites the natives whose size/count LWJGL takes from the Buffer (see BUFFER_SIZES)."""
    rules = [
        ("glBufferData(target, size, ", "glBufferData(target, buffer ? bufferRemainingBytes(ctx, buffer) : size, "),
        ("glBufferSubData(target, offset, size, ", "glBufferSubData(target, offset, data ? bufferRemainingBytes(ctx, data) : size, "),
    ]
    for n in "1234":
        for t in "fi":
            c = "GLfloat" if t == "f" else "GLint"
            rules.append((f"glUniform{n}{t}v(location, count, ({c} *) getBufferAddress(",
                          f"glUniform{n}{t}v(location, bufferRemaining(v) / {n}, ({c} *) getBufferAddress("))
    for n in "234":
        rules.append((f"glUniformMatrix{n}fv(location, count, transpose, (GLfloat *) getBufferAddress(",
                      f"glUniformMatrix{n}fv(location, bufferRemaining(value) / {int(n) * int(n)}, transpose, (GLfloat *) getBufferAddress("))
    for what, arg in (("Textures", "textures"), ("Buffers", "buffers"), ("Framebuffers", "framebuffers"),
                      ("Renderbuffers", "renderbuffers")):
        for verb in ("Gen", "Delete"):
            rules.append((f"gl{verb}{what}(n, (GLuint *) getBufferAddress((java_nio_IntBuffer *) {arg}))",
                          f"gl{verb}{what}(bufferRemaining({arg}), (GLuint *) getBufferAddress((java_nio_IntBuffer *) {arg}))"))
    for old, new in rules:
        assert gl.count(old) == 1, ("expected once in upstream's GL natives", old, gl.count(old))
        gl = gl.replace(old, new)
    return BUFFER_SIZES + gl


